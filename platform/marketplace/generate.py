#!/usr/bin/env python3
"""Generate the simulated internal data product marketplace (docs/marketplace.md).

Analogous to a Snowflake internal marketplace: each published output port is a
*listing*. The listing's metadata comes from the same sources of truth — the
output-port ODCS contract (schema, classification, SLA) and the data product
definition (purpose, owner, type, consumers) — and its physical location is the
medallion layer the dbt model lives in. "Subscribing" = the consumer grant.

Run: `make marketplace`. At M4 this content is published to DataHub as the real
catalog; for now it is a versioned markdown page.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
OUT = REPO_ROOT / "docs" / "marketplace.md"


def _domain_of(path: Path) -> str:
    rel = path.relative_to(REPO_ROOT).parts
    return rel[1] if rel[0] == "domains" else "reference"


def _listings() -> list[dict]:
    listings: list[dict] = []
    for c in sorted(REPO_ROOT.glob("domains/*/contracts/*.odcs.yaml")):  # excludes landing/
        contract = yaml.safe_load(c.read_text(encoding="utf-8")) or {}
        schema = (contract.get("schema") or [{}])[0]
        if "output_port" not in (schema.get("tags") or []):
            continue
        domain = _domain_of(c)
        product = schema.get("name", c.stem)
        # physical location = the medallion layer the dbt model lives in
        location = "—"
        for m in (REPO_ROOT / "domains" / domain / "dbt" / "models").rglob(f"{product}.sql"):
            location = f"{domain}_{m.parent.name}.{product}"
            break
        defn_path = REPO_ROOT / "domains" / domain / "data_products" / f"{product}.yaml"
        defn = yaml.safe_load(defn_path.read_text(encoding="utf-8")) if defn_path.exists() else {}
        listings.append(
            {
                "product": f"{domain}.{product}",
                "domain": domain,
                "location": location,
                "contract": contract,
                "schema": schema,
                "defn": defn or {},
            }
        )
    return listings


def _sla_line(contract: dict) -> str:
    out = []
    for p in contract.get("slaProperties") or []:
        unit = p.get("unit", "")
        out.append(f"{p['property']}={p.get('value')}{unit}")
    return ", ".join(out) or "—"


def _render(listings: list[dict]) -> str:
    lines = [
        "# Internal data product marketplace",
        "",
        "> Generated by `make marketplace` from the output-port ODCS contracts and data",
        "> product definitions — do not edit by hand. A simulated internal marketplace",
        "> (the Snowflake-internal-marketplace analogy): each published output port is a",
        '> listing; "subscribing" is a consumer grant. Published to DataHub at M4.',
        "",
        f"**{len(listings)} published data product(s).**",
        "",
        "| Data product | Type | Owner | Location | Purpose |",
        "|---|---|---|---|---|",
    ]
    for ls in listings:
        d = ls["defn"]
        owner = (d.get("owner") or {}).get("team", "—")
        row = f"| `{ls['product']}` | {d.get('type', '—')} | {owner} "
        row += f"| `{ls['location']}` | {d.get('purpose', '—')} |"
        lines.append(row)
    lines.append("")

    for ls in listings:
        d = ls["defn"]
        c = ls["contract"]
        lines += [
            f"## `{ls['product']}`",
            "",
            f"- **Type:** {d.get('type', '—')}",
            f"- **Purpose:** {d.get('purpose', '—')}",
            f"- **Owner (provider):** {(d.get('owner') or {}).get('team', '—')}",
            f"- **Physical location:** `{ls['location']}`",
            f"- **Contract:** `{c.get('id', '—')}` v{c.get('version', '—')}",
            f"- **SLA:** {_sla_line(c)}",
            "",
            "**Columns**",
            "",
            "| Column | Type | Classification |",
            "|---|---|---|",
        ]
        for p in ls["schema"].get("properties") or []:
            lines.append(
                f"| {p['name']} | {p.get('logicalType', '—')} | {p.get('classification', '—')} |"
            )
        lines += [
            "",
            "**Subscribe** (request access): add your team to the product's `consumers`",
            "",
        ]
        consumers = d.get("consumers") or []
        if consumers:
            for cons in consumers:
                lines.append(f"- `{cons.get('team')}` — {cons.get('use_case', '')}")
        else:
            lines.append("- _no consumers yet_")
        lines.append("")
    return "\n".join(lines) + "\n"


def main() -> int:
    listings = _listings()
    OUT.write_text(_render(listings), encoding="utf-8")
    print(f"Marketplace written: {OUT.relative_to(REPO_ROOT)} ({len(listings)} listing(s)).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
